def HL(X, ROWS, row, step, at=None, top=None):
    """표 행 형광. at=붙인 자리 왼쪽 위, top=붙인 조각의 원래 윗변(행 위치 계산용)"""
    r0, r1 = ROWS[row]
    if at is None: return (step - 1, [X[0] + 3, r0 + 2, X[1] - 3, r1 - 2])
    dy = at[1] - top; dx = at[0] - X[0]
    return (step - 1, [X[0] + dx + 3, r0 + dy + 2, X[1] + dx - 3, r1 + dy - 2])

def ROWPASTE(page, X, ROWS, rows, at, step=None):
    """머리 + 고른 행들을 at부터 차례로 붙임 → (paste 목록, {행: 붙인 y 윗변})"""
    out, pos, y = [], {}, at[1]
    for r in rows:
        r0, r1 = ROWS[r]
        if r == rows[-1]: r1 += 2                     # 마지막 행은 아래 테두리까지
        d = dict(page=page, src=[X[0], r0, X[1], r1], at=[at[0], y])
        if step: d['step'] = step
        out.append(d); pos[r] = (y, r1 - r0); y += r1 - r0
    return out, pos

def HLR(at, X, pos, row, step):
    y, h = pos[row]
    return (step - 1, [at[0] + 3, y + 2, at[0] + (X[1] - X[0]) - 3, y + h - 2])

